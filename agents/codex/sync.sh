#!/usr/bin/env bash
# Codex SessionStart hook: fast-forward this repo, rebuild ~/.codex/AGENTS.md
# from the rules, and link skills into ~/.agents/skills. See agents/codex/README.md.

source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"

codex_dir="${CODEX_HOME:-$HOME/.codex}"
skills_dir="${AGENTIC_AGENTS_SKILLS_DIR:-$HOME/.agents/skills}"
marker="<!-- Generated by agentic/agents/codex/sync.sh. Do not edit: changes are overwritten. Put machine-specific instructions in AGENTS.local.md next to this file. -->"

pull_repo || finish codex

# Codex reads a single global AGENTS.md and doesn't look above a repo's root,
# so every rule (global, lang, and org) goes into that one file. Each lang and
# org rule states its own scope.
build_agents_md() {
  local f
  echo "$marker"
  for f in "$repo"/rules/*.md "$repo"/rules/lang/*.md "$repo"/rules/orgs/*.md; do
    [ -e "$f" ] || continue
    echo
    strip_frontmatter "$f"
  done
  if [ -s "$codex_dir/AGENTS.local.md" ]; then
    echo
    cat "$codex_dir/AGENTS.local.md"
  fi
}

if [ -d "$codex_dir" ]; then
  dest="$codex_dir/AGENTS.md"
  if [ -e "$dest" ] && [ "$(head -n 1 "$dest")" != "$marker" ]; then
    note "Left $dest alone: it wasn't generated by this hook. Move its content to $codex_dir/AGENTS.local.md and delete it to let the hook manage it."
  else
    tmp="$(mktemp "$codex_dir/.AGENTS.md.XXXXXX")"
    build_agents_md > "$tmp"
    if [ -e "$dest" ] && cmp -s "$tmp" "$dest"; then
      rm -f "$tmp"
    else
      mv "$tmp" "$dest" && note "Rebuilt $dest. Changes take effect next session."
    fi
    size="$(wc -c < "$dest" | tr -d ' ')"
    [ "$size" -gt 32768 ] &&
      note "$dest is $size bytes, over Codex's default 32 KiB project_doc_max_bytes, so Codex may not load all of it. Raise project_doc_max_bytes or trim rules."
  fi
fi

link_skills "$skills_dir"

finish codex
